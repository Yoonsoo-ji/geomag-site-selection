def render_docx(S, P, path: Path) -> Path:
    from docx import Document
    from docx.enum.text import WD_ALIGN_PARAGRAPH
    from docx.oxml import OxmlElement
    from docx.oxml.ns import qn
    from docx.shared import Cm, Pt, RGBColor

    NAVY = RGBColor(0x1F, 0x38, 0x64)
    RED = RGBColor(0xB2, 0x18, 0x2B)
    GREY = RGBColor(0x55, 0x55, 0x55)
    TEAL = RGBColor(0x0E, 0x6B, 0x6B)

    doc = Document()
    st = doc.styles["Normal"]
    st.font.name = "맑은 고딕"
    st._element.rPr.rFonts.set(qn("w:eastAsia"), "맑은 고딕")
    st.font.size = Pt(10.5)
    st.paragraph_format.space_after = Pt(5)
    st.paragraph_format.line_spacing = 1.4
    for lv, size in ((0, 17), (1, 13), (2, 11.5)):
        hs = doc.styles[f"Heading {lv + 1}"]
        hs.font.name = "맑은 고딕"
        hs._element.rPr.rFonts.set(qn("w:eastAsia"), "맑은 고딕")
        hs.font.size = Pt(size)
        hs.font.color.rgb = NAVY
        hs.paragraph_format.keep_with_next = True
    for s in doc.sections:
        s.left_margin = s.right_margin = Cm(2.2)
        s.top_margin = s.bottom_margin = Cm(1.8)

    def shade(cell, hexc):
        el = OxmlElement("w:shd")
        el.set(qn("w:fill"), hexc)
        cell._tc.get_or_add_tcPr().append(el)

    def repeat_header(row):
        """⚠️ 표가 쪽을 넘으면 머리행이 «빈 줄»로 보인다 — 반복시킨다."""
        el = OxmlElement("w:tblHeader")
        el.set(qn("w:val"), "true")
        row._tr.get_or_add_trPr().append(el)

    def para(txt, size=10.5, color=None, bold=False, indent=0.0, after=5):
        p = doc.add_paragraph()
        p.paragraph_format.space_after = Pt(after)
        if indent:
            p.paragraph_format.left_indent = Cm(indent)
        r = p.add_run(txt)
        r.font.size = Pt(size)
        r.font.bold = bold
        if color is not None:
            r.font.color.rgb = color
        return p

    # ── 표지 ───────────────────────────────────────────────────
    total = sum(x[3] for x in S)
    doc.add_paragraph()
    for txt, size, col, bold in (
            (TITLE, 21, NAVY, True),
            (SUBTITLE, 12.5, GREY, False),
            (f"실시 {P['generated']}", 11, GREY, False)):
        p = doc.add_paragraph()
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        r = p.add_run(txt)
        r.font.size = Pt(size)
        r.font.bold = bold
        r.font.color.rgb = col
    doc.add_paragraph()
    para(f"발표자료 : {DECK}", 10, GREY)
    para(f"장면 {len(S)}개 · 본문 합계 약 {total:.0f}분 (질의 별도)", 10, GREY)
    para("이 대본의 수치는 발표자료와 같은 파일에서 읽습니다. "
         "명단이나 계산이 바뀌면 다시 생성해 주십시오.", 9.5, GREY)

    # ── 진행 안내 ──────────────────────────────────────────────
    doc.add_page_break()
    doc.add_heading("진행 전에", level=1)
    para("대본은 그대로 읽으셔도 되고 자기 말로 바꾸셔도 됩니다. "
         "다만 【짚을 것】에 적힌 문장은 빠뜨리지 말아 주십시오 — "
         "그 문장들이 현장에서 실제 사고를 막습니다.", after=8)

    doc.add_heading("조작", level=2)
    for t in PREP:
        para("· " + t, 10, indent=0.4, after=3)

    doc.add_heading("이렇게 말하면 안 됩니다", level=2)
    para("아래 일곱 가지는 이 프로젝트가 오래 다듬어 온 표현 규약입니다. "
         "무심코 깨기 쉬우니 한 번 읽고 들어가 주십시오.", 10, after=6)
    t = doc.add_table(rows=1, cols=2)
    t.style = "Table Grid"
    for i, h in enumerate(("이렇게 말하면 안 됩니다", "이렇게 말합니다")):
        c = t.rows[0].cells[i]
        c.text = ""
        r = c.paragraphs[0].add_run(h)
        r.font.bold = True
        r.font.size = Pt(10)
        r.font.color.rgb = NAVY
        shade(c, "EAF0F6")
    repeat_header(t.rows[0])
    for bad, good in FORBIDDEN:
        row = t.add_row().cells
        for cell, txt, col in ((row[0], bad, RED), (row[1], good, None)):
            cell.text = ""
            rr = cell.paragraphs[0].add_run(txt)
            rr.font.size = Pt(9.5)
            if col is not None:
                rr.font.color.rgb = col
    t.columns[0].width = Cm(5.6)
    t.columns[1].width = Cm(10.0)

    doc.add_heading("시간 배분", level=2)
    t2 = doc.add_table(rows=1, cols=4)
    t2.style = "Table Grid"
    for i, h in enumerate(("장면", "제목", "분", "누적")):
        c = t2.rows[0].cells[i]
        c.text = ""
        r = c.paragraphs[0].add_run(h)
        r.font.bold = True
        r.font.size = Pt(9.5)
        r.font.color.rgb = NAVY
        shade(c, "EAF0F6")
    repeat_header(t2.rows[0])
    acc = 0.0
    for n, tag, title, mins, *_ in S:
        acc += mins
        row = t2.add_row().cells
        for cell, txt in zip(row, (f"{n:02d}", f"{tag} — {title}",
                                   f"{mins:.1f}", f"{acc:.1f}")):
            cell.text = ""
            pp = cell.paragraphs[0]
            pp.paragraph_format.space_after = Pt(0)
            pp.paragraph_format.line_spacing = 1.0
            rr = pp.add_run(txt)
            rr.font.size = Pt(8.5)
    for w, col in zip((1.4, 9.6, 1.6, 1.8), t2.columns):
        col.width = Cm(w)

    # ── 장면별 대본 ────────────────────────────────────────────
    doc.add_page_break()
    doc.add_heading("장면별 대본", level=1)
    for n, tag, title, mins, talk, points, qa in S:
        doc.add_heading(f"{n:02d}  {tag} — {title}", level=2)
        para(f"예상 {mins:.1f}분", 9.5, TEAL, after=4).paragraph_format             .keep_with_next = True
        for line in talk.split("\n"):
            para(line, 10.5, indent=0.3, after=4)
        if points:
            para("【 짚을 것 】", 10, NAVY, bold=True, after=3)
            for t3 in points:
                para("· " + t3, 9.8, indent=0.4, after=2)
        for q, a in qa:
            para("【 질문이 나오면 】", 10, NAVY, bold=True, after=3)
            para("Q. " + q, 9.8, RED, indent=0.4, after=2)
            para("A. " + a, 9.8, indent=0.4, after=4)
        doc.add_paragraph().paragraph_format.space_after = Pt(2)

    doc.save(str(path))
    return path


